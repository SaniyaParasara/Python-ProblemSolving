# 6. Write a program to illustrate the use of tuples and sets with basic operations.

# Create a tuple
t = (1, 2, 3, 4, 5)

# Display the tuple
print("Tuple:", t)

# Display the length of the tuple
print("Length of tuple:", len(t))

# Access and display the first element
print("First element of tuple:", t[0])

# Access and display the last element
print("Last element of tuple:", t[-1])

# Count the occurrences of element 2
print("Count of 2 in tuple:", t.count(2))

# Find the index of element 3
print("Index of 3 in tuple:", t.index(3))
