# 8. Write a program to explain mutable and immutable objects in Python.

# Create a mutable object (List)
a = [1, 2, 3, 4, 5]

# Modify the list by adding a new element
a.append(6)

# Display the modified list
print("List:", a)

# Create an immutable object (String)
b = "hello"

# Display the string
print("String:", b)
